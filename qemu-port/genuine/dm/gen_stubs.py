#!/usr/bin/env python3
"""gen_stubs.py -- generate dm_stubs.S: one link-time stub per undefined symbol.

Reads the `nm -u` output of a pass-1 link (elf path as argv[1], or a symbol
list on stdin) and emits assembly giving every symbol a body of
`xor %eax,%eax; ret` (returns 0 / KErrNone; harmless for void functions and
constructors). Symbols in SPECIAL get a bespoke body instead:

  _ZN4User5PanicERK7TDesC16i   User::Panic -> prints via the IAT slot, parks

Excluded (provided elsewhere): app_main (dm_glue.cpp), __divdi3 (libgcc),
anything already defined in the pass-1 elf.

Usage:
  python3 genuine/dm/gen_stubs.py INPUT... out.S iat_slot_sym
  (INPUTs are .o files or a pass-1 .elf)
"""
import subprocess
import sys
from pathlib import Path

PANIC_SYM = "_ZN4User5PanicERK7TDesC16i"
EXCLUDE = {"app_main", "__divdi3", "_start"}


def main():
    *inputs, out_path, slot = sys.argv[1:]
    if not out_path.endswith(".S"):
        out_path, slot = "genuine/dm/dm_stubs.S", out_path
    syms = set()
    defined = set()
    for inp in inputs:
        und = subprocess.run(["nm", "-u", inp], capture_output=True, text=True).stdout
        syms |= {ln.split()[-1] for ln in und.splitlines() if ln.strip()}
        dfn = subprocess.run(["nm", "--defined-only", inp], capture_output=True, text=True).stdout
        defined |= {ln.split()[-1] for ln in dfn.splitlines() if ln.strip()}
    syms = sorted(syms - defined)
    lines = [
        "/* Generated by genuine/dm/gen_stubs.py -- link-time stubs for the",
        "   EUSER/EFSRV symbols the genuine domainsrv.cpp references. Our",
        "   pipeline imports only EUSER ord 915, so these satisfy the linker;",
        "   they are NOT called on the smoke path (app_main exercises only",
        "   domaincfg.cpp). Full bring-up binds the real exports via the",
        "   pack_multi.py thunk pipeline. */",
        ".section .text",
    ]
    for s in syms:
        if s in EXCLUDE:
            continue
        lines.append(f".globl {s}")
        lines.append(f".type {s}, @function")
        lines.append(f"{s}:")
        if s == PANIC_SYM:
            lines += [
                "    push %ebx",
                f"    mov ${slot}, %ebx",
                "    mov (%ebx), %eax",
                "    test %eax, %eax",
                "    je 1f",
                "    push $0x1000",
                "    push $dm_panic_msg",
                "    call *%eax",
                "    add $8, %esp",
                "1:  pop %ebx",
                "    hlt",
                "    jmp 1b",
            ]
        else:
            lines += ["    xor %eax, %eax", "    ret"]
        lines.append(f".size {s}, .-{s}")
    lines += [
        '.section .rodata',
        '.globl dm_panic_msg',
        'dm_panic_msg:',
        '    .asciz "DM: User::Panic stub reached (reason in edx)\\r\\n"',
        '.section .note.GNU-stack,"",@progbits',
        "",
    ]
    Path(out_path).write_text("\n".join(lines))
    print(f"wrote {out_path} with {len([s for s in syms if s not in EXCLUDE])} stubs")


if __name__ == "__main__":
    main()
